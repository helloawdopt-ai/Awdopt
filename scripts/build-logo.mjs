// Outlines the "awdopt" wordmark (Unbounded 800) into SVG paths, following docs/DESIGN.md §2.
// Writes src/components/brand/logo-geometry.ts, public/brand/*.svg and src/app/icon.svg.
// Run once after a logo spec change: npm run logo
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import opentype from "opentype.js";

const root = new URL("../", import.meta.url);
const woff = readFileSync(new URL("node_modules/@fontsource/unbounded/files/unbounded-latin-800-normal.woff", root));
const font = opentype.parse(woff.buffer.slice(woff.byteOffset, woff.byteOffset + woff.byteLength));

// Colours come from tokens.css so no hex lives in source.
const tokens = Object.fromEntries(
  [...readFileSync(new URL("src/app/tokens.css", root), "utf8").matchAll(/--([a-z-]+):\s*(#[0-9a-f]{6})/gi)].map(
    (m) => [m[1], m[2]],
  ),
);

// Units: 1em = 100. Spec values from DESIGN.md §2.
const EM = 100;
const TRACK = -0.04;
const PAD = { top: 4, x: 14, bottom: 10 };
const RADIUS = 32;
const GAP = 4; // margin-right of the bubble
const BW = 10; // room reserved for the border; the drawn stroke is thinner (see Logo.tsx)
const TAIL = { left: 24, w: 30, h: 25 };

const scale = EM / font.unitsPerEm;
const ascent = font.tables.hhea.ascender * scale;
const descent = -font.tables.hhea.descender * scale;
const opts = { kerning: true, letterSpacing: TRACK };
// CSS adds tracking after the last glyph too; drop it for tight bounds.
const advance = (t) => font.getAdvanceWidth(t, EM, opts) - TRACK * EM;
const r = (n) => Math.round(n * 100) / 100;

// Bubble padding box around "aw": inline background covers the font's content area plus padding.
const awW = advance("aw");
const baseline = BW + PAD.top + ascent;
const pad = { x: BW, y: BW, w: PAD.x * 2 + awW, h: PAD.top + ascent + descent + PAD.bottom };
const awX = pad.x + PAD.x;
const doptX = pad.x + pad.w + BW + GAP;
const doptPath = font.getPath("dopt", doptX, baseline, EM, opts);
const awPath = font.getPath("aw", awX, baseline, EM, opts);

// Tail: SVG viewBox 0 0 26 22 placed at the padding box's bottom-left, top = 100% - half border.
const sx = TAIL.w / 26;
const sy = TAIL.h / 22;
const tx = pad.x + TAIL.left;
const ty = pad.y + pad.h - BW / 2;
const pt = (x, y) => `${r(tx + x * sx)},${r(ty + y * sy)}`;
const tail = {
  fill: [pt(0, -3), pt(26, -3), pt(4, 20)].join(" "),
  line: [pt(0, 0), pt(4, 20), pt(26, 0)].join(" "),
  stroke: r(6 * sx),
};

const doptBox = doptPath.getBoundingBox();
const width = r(doptX + advance("dopt"));
const height = r(Math.max(pad.y + pad.h + BW, ty + 20 * sy + tail.stroke, doptBox.y2) + 2);

const bubble = { x: r(pad.x), y: r(pad.y), w: r(pad.w), h: r(pad.h), rx: RADIUS };
const geometry = {
  viewBox: `0 0 ${width} ${height}`,
  width,
  height,
  bubble,
  tail,
  aw: awPath.toPathData(2),
  dopt: doptPath.toPathData(2),
};

// Icon: the bubble alone (no "dopt"), centred in a 100×100 rounded square.
const iconScale = 62 / (pad.w + BW * 2);
const iconOffX = (100 - (pad.w + BW * 2) * iconScale) / 2;
const iconOffY = (100 - (pad.h + BW * 2 + TAIL.h * 0.6) * iconScale) / 2;
const icon = { scale: r(iconScale), x: r(iconOffX), y: r(iconOffY) };

writeFileSync(
  new URL("src/components/brand/logo-geometry.ts", root),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.\nexport const LOGO = ${JSON.stringify(geometry, null, 2)} as const;\n\nexport const ICON = ${JSON.stringify(icon, null, 2)} as const;\n`,
);

// Standalone SVG files need literal colours (they render outside the app's CSS).
const c = tokens;
const markBody = ({ text = c.ink, aw = c.ink, outline = true, stroke = 2.5 }) => `
  <rect x="${bubble.x}" y="${bubble.y}" width="${bubble.w}" height="${bubble.h}" rx="${bubble.rx}" fill="${c.bubble}"${outline ? ` stroke="${c.ink}" stroke-width="${stroke}" vector-effect="non-scaling-stroke"` : ""}/>
  <polygon points="${tail.fill}" fill="${c.bubble}"/>
  ${outline ? `<polyline points="${tail.line}" fill="none" stroke="${c.ink}" stroke-width="${tail.stroke}" stroke-linejoin="round"/>` : ""}
  <path d="${geometry.aw}" fill="${aw}"/>
  <path d="${geometry.dopt}" fill="${text}"/>`;
const svg = (vb, body, w, h) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb}" width="${w}" height="${h}" role="img" aria-label="AWDOPT">${body}\n</svg>\n`;

const iconBody = (withTail, border) => `
  <rect x="${border / 2}" y="${border / 2}" width="${100 - border}" height="${100 - border}" rx="22" fill="${c.primary}" stroke="${c.ink}" stroke-width="${border}"/>
  <g transform="translate(${icon.x} ${icon.y}) scale(${icon.scale})">
    <rect x="${bubble.x}" y="${bubble.y}" width="${bubble.w}" height="${bubble.h}" rx="${bubble.rx}" fill="${c.bubble}" stroke="${c.ink}" stroke-width="${withTail ? 6 : 7}"/>
    ${withTail ? `<polygon points="${tail.fill}" fill="${c.bubble}"/><polyline points="${tail.line}" fill="none" stroke="${c.ink}" stroke-width="${tail.stroke}" stroke-linejoin="round"/>` : ""}
    <path d="${geometry.aw}" fill="${c.ink}"/>
  </g>`;

mkdirSync(new URL("public/brand/", root), { recursive: true });
const w = 480;
const h = r((w * height) / width);
const pageW = width + 40;
const pageH = height + 40;
writeFileSync(new URL("public/brand/logo-primary.svg", root), svg(geometry.viewBox, markBody({}), w, h));
writeFileSync(
  new URL("public/brand/logo-reversed.svg", root),
  svg(
    `-20 -20 ${pageW} ${pageH}`,
    `\n  <rect x="-20" y="-20" width="${pageW}" height="${pageH}" fill="${c.ink}"/>` +
      markBody({ text: c.bg, aw: c.ink, outline: false }),
    w,
    r((w * pageH) / pageW),
  ),
);
writeFileSync(new URL("public/brand/icon.svg", root), svg("0 0 100 100", iconBody(true, 3), 512, 512));
writeFileSync(new URL("src/app/icon.svg", root), svg("0 0 100 100", iconBody(false, 4.5), 32, 32));

console.log(`logo ${geometry.viewBox}; icon scale ${icon.scale}`);
